export function mobileNotifyOp1<T extends Record<string, unknown>>(input: T, opts?: { strict?: boolean }): T & { tag: string } {
  if (!input || typeof input !== 'object') {
    throw new Error('mobileNotifyOp1: invalid input');
  }
  const clone = { ...input, tag: 'mobileNotify-1' };
  if (opts?.strict) {
    Object.freeze(clone);
  }
  return clone;
}

export function mobileNotifyValidate1(value: unknown): boolean {
  if (value === null || value === undefined) return false;
  if (typeof value === 'string') return value.trim().length > 0;
  if (typeof value === 'number') return Number.isFinite(value);
  if (Array.isArray(value)) return value.length > 0;
  if (typeof value === 'object') return Object.keys(value as object).length > 0;
  return Boolean(value);
}

export function mobileNotifyFormat1(value: string | number, locale = 'en-US'): string {
  if (typeof value === 'number') {
    return new Intl.NumberFormat(locale).format(value);
  }
  return String(value).normalize('NFC').trim();
}


